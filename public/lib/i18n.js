// User interface texts in German and English, shared by the browser, the server and the tests.
// Placeholders: {name}. Numbers passed as placeholders are formatted for the language.
// Keys ending in ".html" contain trusted markup and are inserted as HTML.

export const LANGUAGES = ['de', 'en'];
export const LOCALES = { de: 'de-DE', en: 'en-GB' };

/** 'de' or 'en' for a language tag like "de-AT", "en-US" or "de_DE.UTF-8"; null for anything else. */
export function normalizeLanguage(value) {
  if (typeof value !== 'string') return null;
  const code = value.trim().toLowerCase().slice(0, 2);
  return LANGUAGES.includes(code) ? code : null;
}

/** First supported language among the candidates (e.g. navigator.languages); English otherwise. */
export function detectLanguage(candidates) {
  for (const candidate of candidates ?? []) {
    const language = normalizeLanguage(candidate);
    if (language) return language;
  }
  return 'en';
}

const paramFormats = new Map();

function formatParam(lang, value) {
  if (typeof value !== 'number') return String(value);
  const locale = LOCALES[lang] ?? LOCALES.de;
  let format = paramFormats.get(locale);
  if (!format) {
    format = new Intl.NumberFormat(locale, { maximumFractionDigits: 3 });
    paramFormats.set(locale, format);
  }
  return format.format(value);
}

/** Text for `key` in `lang` (falls back to German, then to the key itself). */
export function t(lang, key, params = {}) {
  const template = MESSAGES[lang]?.[key] ?? MESSAGES.de[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (whole, name) =>
    params && name in params ? formatParam(lang, params[name]) : whole);
}

/** Plural form: "<key>_one" for exactly 1, "<key>_other" otherwise. {count} is filled in. */
export function tn(lang, key, count, params = {}) {
  return t(lang, `${key}_${count === 1 ? 'one' : 'other'}`, { count, ...params });
}

